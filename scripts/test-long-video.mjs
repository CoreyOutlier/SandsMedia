// Synthetic-only acceptance for the selected 5 GiB / two-hour video limits.
// Run against the dedicated local test database and Drive root. Never print
// bodies, identities, signed URLs, credentials, filenames or raw exceptions.
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {randomUUID,createHash} from 'node:crypto';
import {encode} from 'next-auth/jwt';
import pg from 'pg';
import {drive as createDrive,auth as googleAuth} from 'googleapis/build/src/apis/drive/index.js';

let stage='setup',db,cookie,origin;
const maxBytes=5*1024**3;
const maxDuration=2*60*60;
const digest=bytes=>createHash('sha256').update(bytes).digest('hex');

async function request(path,body,expected=200){
 const response=await fetch(origin+path,{
  method:body===undefined?'GET':'POST',headers:{cookie,origin,'Content-Type':'application/json'},
  body:body===undefined?undefined:JSON.stringify(body),signal:AbortSignal.timeout(90000),
 });
 if(response.status!==expected){
  let code='UNKNOWN';try{const data=await response.json();if(/^[A-Z_]+$/.test(data.error??''))code=data.error;}catch{}
  throw new Error(`HTTP_${response.status}_${code}`);
 }
 return response;
}
async function api(path,body,expected){return(await request(path,body,expected)).json();}
function inputFor(plan){
 return {uploadId:randomUUID(),kind:'general',title:'Synthetic long-video check',
  date:new Date().toISOString().slice(0,10),description:'Generated fixture only',uploadedBy:'Automated test',
  consented:false,formOnFile:false,files:[plan]};
}
function planFor(bytes,durationS){
 return {key:randomUUID(),fingerprint:digest(bytes),kind:'video',label:'other',mimeType:'video/mp4',
  bytes:bytes.length,width:320,height:240,durationS,title:'Synthetic long footage'};
}

try{
 origin=process.env.APP_URL;
 assert.equal(origin,'http://localhost:3102');
 assert.equal(new URL(process.env.DATABASE_URL).pathname,'/sandsmedia_upload_test');
 assert.equal(Number(process.env.MAX_VIDEO_MB),5120);
 assert.ok((process.env.ALLOWED_EMAILS??'').split(',').map(value=>value.trim().toLowerCase()).includes('allowed@example.test'));
 db=new pg.Client({connectionString:process.env.DATABASE_URL,connectionTimeoutMillis:20000});await db.connect();
 const clinic=(await db.query('SELECT drive_root_folder_id FROM clinics WHERE slug=$1',[process.env.CLINIC_SLUG??'dr-sands'])).rows[0];
 assert.ok(clinic);assert.equal(clinic.drive_root_folder_id,process.env.DRIVE_ROOT_FOLDER_ID);
 const jwt=await encode({secret:process.env.AUTH_SECRET,salt:'authjs.session-token',token:{sub:'long-video-test',email:'allowed@example.test',verifiedGoogle:true},maxAge:3600});
 cookie=`authjs.session-token=${jwt}`;
 const key=JSON.parse(Buffer.from(process.env.GOOGLE_SERVICE_ACCOUNT_JSON,'base64').toString());
 const drive=createDrive({version:'v3',auth:new googleAuth.GoogleAuth({credentials:key,scopes:['https://www.googleapis.com/auth/drive']})});

 stage='size_and_duration_boundaries';
 // Start-only boundary test reserves no Drive upload URL and transfers no 5 GiB
 // object. Actual transfer behavior is exercised below with small real videos.
 const boundary=planFor(Buffer.from('synthetic-boundary'),maxDuration);boundary.bytes=maxBytes;
 const boundaryInput=inputFor(boundary),started=await api('/api/uploads/start',boundaryInput);
 assert.equal(started.files[0].bytes,maxBytes);assert.equal(started.files[0].durationS,maxDuration);
 assert.ok(started.files.every(file=>!file.driveId&&!file.confirmed));
 assert.equal((await api(`/api/uploads/${started.id}/status`)).files[0].bytes,maxBytes);
 for(const invalid of [{...boundary,bytes:maxBytes+1},{...boundary,durationS:maxDuration+0.001}]){
  const rejected=inputFor(invalid);await api('/api/uploads/start',rejected,400);
  assert.equal((await db.query('SELECT count(*)::int AS count FROM upload_batches WHERE id=$1',[rejected.uploadId])).rows[0].count,0);
 }

 for(const duration of [242,maxDuration]){
  stage=`actual_${duration}_second_upload`;
  const fixture=await readFile(new URL(`../qa/upload-fixtures/synthetic-${duration}s.mp4`,import.meta.url));
  // MP4 free-box padding crosses the real 8 MiB chunk boundary without changing
  // the real video duration or allocating a multi-gigabyte synthetic fixture.
  const free=Buffer.alloc(9*1024*1024);free.writeUInt32BE(free.length,0);free.write('free',4);
  const bytes=Buffer.concat([fixture,free]),plan=planFor(bytes,duration),input=inputFor(plan);
  // A slow Drive video-metadata job may outlive one check. Reuse only an
  // unfinished fixture with the exact generated bytes, then let the normal
  // API enforce ownership. Never create another copy just to retry metadata.
  const previous=(await db.query(`SELECT b.id,b.manifest FROM upload_batches b
   JOIN general_uploads g ON b.general_upload_id=g.id
   WHERE g.title=$1 AND g.finished_at IS NULL
    AND b.manifest->0->>'fingerprint'=$2
    AND (b.manifest->0->>'bytes')::bigint=$3
    AND (b.manifest->0->>'durationS')::numeric=$4
   ORDER BY g.created_at DESC LIMIT 1`,['Synthetic long-video check',plan.fingerprint,plan.bytes,duration])).rows[0];
  if(previous){input.uploadId=previous.id;plan.key=previous.manifest[0].key;}
  const batch=await api('/api/uploads/start',input);
  assert.equal((await api('/api/uploads/start',input)).id,batch.id);
  await api(`/api/uploads/${batch.id}/finish`,{},409);
  const signed=await api(`/api/uploads/${batch.id}/sign`,{key:plan.key});
  if(!signed.complete){
   assert.ok(signed.url);const cut=8*1024*1024;
   let response=await fetch(signed.url,{method:'PUT',headers:{'Content-Type':plan.mimeType,'Content-Range':`bytes 0-${cut-1}/${bytes.length}`},body:bytes.subarray(0,cut),signal:AbortSignal.timeout(120000)});
   assert.equal(response.status,308);
   response=await fetch(signed.url,{method:'PUT',headers:{'Content-Range':`bytes */${bytes.length}`},body:Buffer.alloc(0),signal:AbortSignal.timeout(60000)});
   assert.equal(response.status,308);assert.equal(response.headers.get('range'),`bytes=0-${cut-1}`);
   response=await fetch(signed.url,{method:'PUT',headers:{'Content-Type':plan.mimeType,'Content-Range':`bytes ${cut}-${bytes.length-1}/${bytes.length}`},body:bytes.subarray(cut),signal:AbortSignal.timeout(120000)});
   assert.ok([200,201].includes(response.status));
  }

  stage=`actual_${duration}_second_drive_metadata`;
  let actual;
  for(let attempt=0;attempt<15;attempt++){
   actual=(await drive.files.get({fileId:signed.driveId,supportsAllDrives:true,fields:'size,videoMediaMetadata(durationMillis)'})).data;
   if(actual.videoMediaMetadata?.durationMillis)break;
   await new Promise(resolve=>setTimeout(resolve,2000));
  }
  assert.equal(Number(actual.size),bytes.length);
  // Google may expose duration only after asynchronous video processing. A
  // valid original must still save while its preview is processing. Fixtures
  // are independently duration-checked by the AVFoundation generator.
  const driveDuration=actual.videoMediaMetadata?.durationMillis;
  if(driveDuration&&Number(driveDuration)!==duration*1000)throw new Error('CHECK_DRIVE_DURATION_MISMATCH');
  if(!driveDuration)console.info(`Drive video metadata is still processing for the synthetic ${duration}-second fixture; original upload checks continue.`);
  stage=`actual_${duration}_second_original_hash`;
  const downloaded=await drive.files.get({fileId:signed.driveId,supportsAllDrives:true,alt:'media'},{responseType:'arraybuffer'});
  assert.equal(digest(Buffer.from(downloaded.data)),digest(bytes));
  stage=`actual_${duration}_second_confirmation`;
  assert.equal((await api(`/api/uploads/${batch.id}/media`,{key:plan.key})).confirmed,true);
  assert.equal((await api(`/api/uploads/${batch.id}/media`,{key:plan.key})).confirmed,true);
  stage=`actual_${duration}_second_completion`;
  const result=await api(`/api/uploads/${batch.id}/finish`,{});assert.equal(result.count,1);
  assert.equal((await api(`/api/uploads/${batch.id}/finish`,{})).count,1);
  const status=await api(`/api/uploads/${batch.id}/status`);assert.equal(status.finished,true);assert.equal(status.files[0].confirmed,true);
  stage=`actual_${duration}_second_database`;
  const stored=(await db.query('SELECT m.bytes,m.duration_s,g.finished_at FROM general_media m JOIN general_uploads g ON m.general_upload_id=g.id WHERE g.upload_id=$1',[batch.id])).rows;
  assert.equal(stored.length,1);assert.equal(BigInt(stored[0].bytes),BigInt(bytes.length));assert.equal(stored[0].duration_s,duration);assert.ok(stored[0].finished_at);
  console.info(`PASS: synthetic ${duration}-second video saved with verified original bytes${driveDuration?' and Drive duration':'; Drive duration metadata is still processing'}.`);
 }
 console.info('PASS: 5 GiB start boundary, oversize and over-two-hour rejection, actual 242-second and two-hour Drive videos, chunk interruption/resume, original duration, and idempotent confirmation/completion.');
}catch(error){
 console.error('LONG_VIDEO_CHECK_FAILED_'+stage+(/^(HTTP|CHECK)_[A-Z0-9_]+$/.test(error?.message??'')?'_'+error.message:''));process.exitCode=1;
}finally{await db?.end().catch(()=>{});}
